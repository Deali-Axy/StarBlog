export type Locale = "zh" | "en"

export const localeCookie = "starblog.locale"
export const htmlLang = { zh: "zh-CN", en: "en" }

export function parseLocale(value?: string): Locale {
  return value === "en" ? "en" : "zh"
}

export function articleLanguage(locale: Locale, override?: string) {
  if (override === "original") return undefined
  return override || (locale === "en" ? "en" : undefined)
}

export function languageName(code: string, locale: Locale) {
  try {
    return new Intl.DisplayNames([locale], { type: "language" }).of(code) ?? code
  } catch {
    return code
  }
}

